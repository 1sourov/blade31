fun bladeStringsForCode(code: String): BladeStrings = when (code.trim().lowercase()) {
    "bn" -> BengaliBladeStrings
    "hi" -> HindiBladeStrings
    "ur" -> UrduBladeStrings
    "ta" -> TamilBladeStrings
    "te" -> TeluguBladeStrings
    "mr" -> MarathiBladeStrings
    "gu" -> GujaratiBladeStrings
    "pa" -> PunjabiBladeStrings
    "kn" -> KannadaBladeStrings
    "ml" -> MalayalamBladeStrings
    "zh" -> ChineseBladeStrings
    "fa" -> PersianBladeStrings
    "ar" -> ArabicBladeStrings
    "ne" -> NepaliBladeStrings
    "id" -> IndonesianBladeStrings
    "es" -> SpanishBladeStrings
    "fr" -> FrenchBladeStrings
    "pt" -> PortugueseBladeStrings
    "tr" -> TurkishBladeStrings
    else -> EnglishBladeStrings
}

val LocalBladeStrings = staticCompositionLocalOf { EnglishBladeStrings }

@Composable
fun bladeStrings(): BladeStrings = LocalBladeStrings.current
